#!/usr/bin/env node
// Generates apps/web/lib/routine-prompt.generated.ts from routine/ROUTINE_PROMPT.md (the web app serves it to members).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const prompt = readFileSync(resolve(root, 'routine/ROUTINE_PROMPT.md'), 'utf8');
const out = `// GENERATED by scripts/sync-prompt.mjs from routine/ROUTINE_PROMPT.md. Do not edit.\nexport const ROUTINE_PROMPT = ${JSON.stringify(prompt)};\n`;
const target = resolve(root, 'apps/web/lib/routine-prompt.generated.ts');
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(target, 'utf8');
  } catch {}
  if (cur !== out) {
    console.error('✖ apps/web/lib/routine-prompt.generated.ts is out of date: run node scripts/sync-prompt.mjs');
    process.exit(1);
  }
  console.log('✓ generated routine prompt is up to date');
} else {
  writeFileSync(target, out);
  console.log('✓ wrote', target);
}
